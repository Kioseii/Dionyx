export function getLibrarySortLabel(sortKey: LibrarySortKey, language: AppLanguage) {
  const copy = uiText[language];

  switch (sortKey) {
    case "artist":
      return copy.sortArtist;
    case "album":
      return copy.sortAlbum;
    case "format":
      return copy.sortFormat;
    case "duration":
      return copy.sortDuration;
    case "title":
    default:
      return copy.sortTitle;
  }
}

export function getEmptyTrack(language: AppLanguage): LibraryTrack {
  const copy = uiText[language];

  return {
    title: copy.emptyTrackTitle,
    artist: copy.emptyTrackArtist,
    album: brandName,
    format: "--",
    quality: copy.emptyTrackQuality,
    duration: "--:--",
    path: "",
  };
}
